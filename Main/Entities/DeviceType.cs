namespace VrdoPdg.Model.Entities
{
    /// <summary>
    /// Тип СКРМ. Определяет подтип СКРМ, порядок перебора алгоритмом
    /// и таблицу МТ, в которой хранятся параметры СКРМ.
    /// </summary>
    public enum DeviceType
    {
        /// <summary>
        /// Управляемые СКРМ (УШР, СТК, СК) с плавно изменяемой загрузкой.
        /// Параметры хранятся в таблице «Узлы» МТ.
        /// </summary>
        Controlled,

        /// <summary>
        /// Коммутируемые СКРМ (шунтирующие реакторы, БСК) с состояниями
        /// «Включено» и «Отключено». Параметры хранятся в таблице «Реакторы» МТ.
        /// </summary>
        Switched,

        /// <summary>
        /// Генераторы, заданное напряжение на шинах которых изменяется
        /// в пределах PQ-диаграммы. Параметры хранятся в таблице «Генераторы УР» МТ.
        /// </summary>
        Generator
    }
}
